"""Коды наблюдений: машинный ключ, а не подпись (§8.2).

Тип наблюдения — колонка фиксированной ширины, по которой строится индекс и
идёт дедуп. В неё складывали человекочитаемое название показателя прямо из
ответа источника, и первое же длинное название уронило весь шаг разведки:

    (psycopg.errors.StringDataRightTruncation)
    value too long for type character varying(48)
    'cbr:fx_usd_rub:Средний номинальный курс за период'

Сорок девять символов против сорока восьми. Отказ приходит на автосбросе
сессии, то есть уносит с собой всё, что шаг успел собрать, — и владелец
видит «в сигналах инвестиций так ничего и нет» при полностью исправном
сборе. Название показателя задаёт источник, оно может быть любой длины, и
надеяться на его краткость нельзя.

Поэтому код собирается здесь и всегда влезает. Пока помещается — остаётся
читаемым: `cbr:fx_usd_rub:sredniy-nominalnyy-kurs`. Не помещается — хвост
заменяется устойчивым отпечатком: `cbr:fx_usd_rub:h7f3a91c2`. Отпечаток
детерминирован, поэтому повторный сбор того же показателя даёт тот же код и
дедуп продолжает работать.

Читаемое название при этом не теряется: оно и так лежит в `source_locator`,
где ему и место — там его никто не ограничивает.
"""

from __future__ import annotations

import hashlib
import re

#: Ширина колонки `research_observations.observation_type`.
#:
#: Держится здесь, а не только в модели: код обязан влезать по построению, а
#: не по счастливому стечению.
MAX_CODE = 96

#: Длина отпечатка, которым заменяется непомещающийся хвост.
_FINGERPRINT = 9  # «h» + 8 шестнадцатеричных

_TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def slug(text: str) -> str:
    """Латинский ключ из произвольного названия.

    Транслитерация, а не отбрасывание кириллицы: `Средний курс` и `Средняя
    ставка` после отбрасывания стали бы одинаково пустыми и слились бы в
    один ряд наблюдений.
    """
    lowered = text.strip().lower()
    out = []
    for char in lowered:
        if char in _TRANSLIT:
            out.append(_TRANSLIT[char])
        elif (char.isalnum() and char.isascii()) or char == "_":
            # Подчёркивание сохраняется: идентификаторы наборов у источников
            # уже машинные (`fx_usd_rub`), и переписывать их в дефисы значит
            # разойтись с тем, как набор называет сам источник.
            out.append(char)
        else:
            out.append("-")
    return re.sub(r"-+", "-", "".join(out)).strip("-")


def observation_code(*parts: str, limit: int = MAX_CODE) -> str:
    """Код наблюдения, гарантированно влезающий в колонку.

    Части соединяются двоеточием — так их читает и человек, и запрос вида
    «все наблюдения ЦБ». Последняя часть — обычно название показателя, и
    именно она урезается: префиксы (источник, набор) опознают ряд, и
    портить их нельзя.
    """
    cleaned = [slug(p) for p in parts if slug(p)]
    if not cleaned:
        return ""
    code = ":".join(cleaned)
    if len(code) <= limit:
        return code

    head = ":".join(cleaned[:-1])
    # Отпечаток считается от исходного хвоста, а не от урезанного: два
    # названия с общим началом обязаны разойтись.
    tail = "h" + hashlib.sha256(cleaned[-1].encode()).hexdigest()[:8]
    if not head:
        return tail[:limit]
    room = limit - len(head) - 1
    if room < _FINGERPRINT:
        # Не помещается даже отпечаток — значит слишком длинны сами
        # префиксы, и урезать приходится всё вместе.
        return ("h" + hashlib.sha256(code.encode()).hexdigest())[:limit]
    # Читаемая часть хвоста плюс отпечаток: `sredniy-nomi…h7f3a91c2`.
    readable = cleaned[-1][: room - _FINGERPRINT - 1].rstrip("-")
    return f"{head}:{readable}-{tail}" if readable else f"{head}:{tail}"


__all__ = ["MAX_CODE", "observation_code", "slug"]
