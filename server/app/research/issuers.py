BY_SECID: dict[str, Issuer] = {issuer.secid: issuer for issuer in REGISTRY}


def of(secid: str) -> Issuer | None:
    """Эмитент по коду бумаги. Код ищется и в полном идентификаторе."""
    if not secid:
        return None
    tail = secid.split(":")[-1].upper()
    return BY_SECID.get(tail)


def in_section(section: str) -> list[Issuer]:
    """Эмитенты одного раздела ОКВЭД.

    Именно это и связывает отраслевое наблюдение Банка России с бумагами:
    спрос измерен по разделу, гипотеза адресуется эмитенту.
    """
    key = (section or "").strip().upper()[:1]
    return [issuer for issuer in REGISTRY if issuer.section == key]


def automatic(issuer: Issuer) -> bool:
    """Хватает ли уверенности на гипотезу без ручной проверки (§9)."""
    return issuer.confidence >= MIN_AUTOMATIC


def coverage() -> dict:
    """Что реестр знает и чего не знает.

    Отдаётся наружу намеренно: «эмитент не найден» и «эмитент найден, но
    ИНН неизвестен» требуют разного, а выглядят одинаково отсутствием
    гипотезы.
    """
    with_inn = [i for i in REGISTRY if i.usable_for_financials]
    return {
        "issuers": len(REGISTRY),
        "sections": sorted({i.section for i in REGISTRY}),
        "with_inn": len(with_inn),
        "without_inn": sorted(i.secid for i in REGISTRY if not i.usable_for_financials),
    }


