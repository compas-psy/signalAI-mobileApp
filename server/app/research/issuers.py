"""Отраслевая принадлежность эмитентов (§9, §13.2).

Зачем понадобился отдельный реестр. Мониторинг предприятий Банка России
даёт спрос по разделам ОКВЭД, а гипотеза адресуется эмитенту. Без связи
между ними сигнал конечного спроса не к чему привязать — движок считает,
шлюз пригодности отвергает, и на экране пусто при полностью исправном
сборе.

Почему не с биржи. MOEX ISS в реестре источников стоит `prohibited`:
автоматический сбор для извлечения прибыли запрещён без договора. То, что
торговый контур приложения ходит на биржу, — отдельное решение владельца,
и распространять его на исследовательский контур нельзя. Взять отрасль
оттуда значило бы обойти собственный правовой шлюз через чёрный ход.

Почему не из ФНС. Открытые наборы ключуются по ИНН, а не по тикеру.
Связь «тикер → ИНН» в них не публикуется: она есть в раскрытии
информации, а оно платное.

Отсюда устройство. Отрасль — публично известный факт, который владелец
может проверить глазами за минуту, и она записана здесь. ИНН — факт того
же рода, но ошибка в нём молча припишет эмитенту чужую отчётность,
поэтому записаны только проверенные, а остальные помечены как
неизвестные. Непроверенная запись не даёт автоматической гипотезы: её
уверенность ниже порога §9, и это не оговорка, а механизм.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal

from .entities import MIN_AUTOMATIC, NAME_AND_JURISDICTION, STRONG_ID

#: Разделы ОКВЭД в той же нарезке, в какой их публикует Банк России.
SECTIONS: dict[str, str] = {
    "A": "сельское хозяйство",
    "B": "добыча полезных ископаемых",
    "C": "обрабатывающие производства",
    "D": "электроэнергетика",
    "E": "водоснабжение и утилизация",
    "F": "строительство",
    "G": "торговля",
    "H": "транспортировка и хранение",
    "I": "гостиницы и общественное питание",
    "J": "информация и связь",
    "K": "финансы и страхование",
    "L": "недвижимость",
}


@dataclass(frozen=True, slots=True)
class Issuer:
    """Эмитент и то, что о нём известно достоверно."""

    secid: str
    name: str
    section: str
    #: ИНН только там, где он проверен. Пустая строка — «не знаем», а не
    #: «нет»: разница решает, можно ли брать по эмитенту отчётность ФНС.
    inn: str = ""

    @property
    def sector_name(self) -> str:
        return SECTIONS.get(self.section, "")

    @property
    def confidence(self) -> Decimal:
        """Насколько можно верить привязке.

        С проверенным ИНН — сильный идентификатор. Без него остаётся
        отраслевая принадлежность: её хватает движку спроса и не хватает
        ничему, что требует отчётности конкретного юридического лица.
        """
        return STRONG_ID if self.inn else NAME_AND_JURISDICTION

    @property
    def usable_for_financials(self) -> bool:
        """Можно ли брать по нему выгрузки ФНС.

        Они ключуются по ИНН. Подставить чужой — приписать эмитенту чужую
        отчётность, и заметить это будет негде.
        """
        return bool(self.inn)


# Отрасль — публично известный факт. ИНН заполнен там, где он проверен по
# открытым наборам ФНС; остальные оставлены пустыми намеренно, и это видно
