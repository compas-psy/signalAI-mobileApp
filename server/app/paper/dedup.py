"""Схлопывание дублирующих бумажных сделок (engine-ТЗ §21).

Живёт отдельным модулем, а не внутри миграции, по одной причине: это
поведение нужно проверять тестом. SQL, спрятанный в файле миграции,
проверить нечем — а он трогает боевые данные и обязан быть доказан.

Инвариант, который восстанавливается: **одна живая сделка на инструмент**.
Быть одновременно в десяти позициях по одному активу — не диверсификация,
а десятикратный риск на нём. Владелец увидел ровно это: десять позиций по
HYPEUSDT подряд, входы 52,2860 … 52,2950 — одна сделка, пересчитанная
десять раз.

Живой остаётся самая ранняя по ``opened_at``: сделка начинается там, где
родился план, и именно её владельцу показали раньше остальных. Прочие
получают собственную причину закрытия — «дубль по инструменту» и
«отменено по сроку» в статистике сливаться не должны.

``CANCELLED``, а не ``CLOSED``: позиции не было, закрывать нечего. Это ещё
и важно для допуска к живым деньгам — он считает только закрытые сделки,
и мусорные записи счётчик не надувают.
"""

from __future__ import annotations

from sqlalchemy import text

LIVE = "status IN ('PENDING','OPEN')"

COLLAPSE_SQL = text(
    f"""
    UPDATE paper_trades AS t
       SET status = 'CANCELLED',
           closed_at = COALESCE(t.closed_at, now()),
           outcome = 'дубль',
           close_reason = 'дубль по инструменту'
      FROM (
            SELECT id,
                   row_number() OVER (
                       PARTITION BY instrument_id
                       ORDER BY opened_at, created_at, id
                   ) AS n
              FROM paper_trades
             WHERE {LIVE}
           ) AS ranked
     WHERE t.id = ranked.id
       AND ranked.n > 1
    """
)


def collapse_duplicates(bind) -> int:
    """Оставить по одной живой сделке на инструмент. Вернуть число снятых.

    ``bind`` — всё, у чего есть ``execute``: и сессия, и соединение
    миграции. Число возвращается, чтобы вызывающий мог сказать вслух,
    сколько записей тронул, а не менять данные молча.
    """
    return bind.execute(COLLAPSE_SQL).rowcount


__all__ = ["COLLAPSE_SQL", "LIVE", "collapse_duplicates"]
