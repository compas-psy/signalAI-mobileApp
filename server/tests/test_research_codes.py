"""Код наблюдения обязан влезать в колонку (§8.2).

Проверяется то, что уже сломалось на живом сервере. В колонку фиксированной
ширины складывали название показателя прямо из ответа ЦБ, и первое же
длинное название уронило весь шаг разведки:

    (psycopg.errors.StringDataRightTruncation)
    value too long for type character varying(48)
    'cbr:fx_usd_rub:Средний номинальный курс за период'

Сорок девять символов против сорока восьми. Отказ приходит на автосбросе
сессии и уносит с собой всё, что шаг успел собрать: владелец видит «в
сигналах инвестиций так ничего и нет» при полностью исправном сборе.
"""

from __future__ import annotations

from app.research.codes import MAX_CODE, observation_code, slug


def test_та_самая_строка_которая_уронила_разведку():
    code = observation_code("cbr", "fx_usd_rub", "Средний номинальный курс за период")

    assert len(code) <= MAX_CODE
    assert code.startswith("cbr:fx_usd_rub:")


def test_код_влезает_при_любой_длине_названия():
    # Название задаёт источник. Надеяться на его краткость нельзя: контракт
    # может измениться в любой момент, и падать от этого разведка не должна.
    code = observation_code("cbr", "fx_usd_rub", "показатель " * 40)

    assert len(code) <= MAX_CODE


def test_разные_показатели_не_сливаются_в_один_ряд():
    """Дедуп идёт по типу: слияние означало бы потерю одного из рядов."""
    first = observation_code("cbr", "credit", "Ставка по кредитам " * 20 + "юрлицам")
    second = observation_code("cbr", "credit", "Ставка по кредитам " * 20 + "физлицам")

    assert first != second


def test_повторный_сбор_даёт_тот_же_код():
    """Иначе дедуп перестаёт работать и факт удваивается на каждом прогоне."""
    name = "Средний номинальный курс за период"

    assert observation_code("cbr", "fx", name) == observation_code("cbr", "fx", name)


def test_короткое_название_остаётся_читаемым():
    assert observation_code("fns", "plan", "bfo") == "fns:plan:bfo"


def test_кириллица_транслитерируется_а_не_отбрасывается():
    # Отбрасывание превратило бы «Средний курс» и «Средняя ставка» в
    # одинаково пустой хвост, то есть слило бы два разных ряда в один.
    assert slug("Средний курс") != slug("Средняя ставка")
    assert slug("Средний курс") == "sredniy-kurs"


def test_пустые_части_не_оставляют_дыр():
    assert observation_code("cbr", "", "ставка") == "cbr:stavka"
