/// Роль токена Т-Инвестиций.
///
/// Токенов три, и это не удобство, а граница безопасности. Токен Invest API
/// привязан к пользователю, а не к счёту: один токен с правом торговли видит
/// **все** счета владельца и может отправить заявку с любого. Ограничить его
/// на стороне брокера нельзя — значит нельзя и заводить один такой токен.
///
/// Поэтому права разделены там, где их выдаёт брокер:
///
/// * [sandbox] — песочница. Настоящих денег за ним нет вовсе, на нём
///   проверяются стратегии.
/// * [invest] — **только чтение**. За ним стоит основной капитал, и
///   приложение по нему лишь считает пакеты и предлагает ребаланс. Сделки
///   по этим рекомендациям владелец совершает сам; заявок отсюда не уходит
///   ни одной, и это проверяется в коде, а не подразумевается.
/// * [trade] — торговый счёт под идеи. Только он получает заявки, и только
///   он один: это единственное место, где приложение распоряжается деньгами.
///
/// Роль хранится в имени слота хранилища ключей, поэтому токены не
/// перезаписывают друг друга и не подменяются местами.
library;

enum TInvestRole {
  sandbox('sandbox', 'Песочница',
      'бумажные сделки уходят сюда же — настоящих денег нет'),
  invest('invest', 'Инвестиции · чтение',
      'капитал и пакеты; заявки не отправляются никогда'),
  trade('trade', 'Идеи · торговля', 'единственный счёт, с которого уходят заявки');

  const TInvestRole(this.slot, this.title, this.meaning);

  /// Имя слота в хранилище ключей. Совпадает с тем, что раньше занимал
  /// режим площадки, поэтому отдельного хранилища не потребовалось.
  final String slot;

  final String title;
  final String meaning;

  /// Может ли токен этой роли отправлять заявки.
  ///
  /// Песочница может: там нет настоящих денег, и весь её смысл в том, чтобы
  /// прогонять сделки. Инвестиционный — нет, и это главное правило всей
  /// схемы: рекомендация не превращается в ордер сама.
  bool get canTrade => this != TInvestRole.invest;

  /// Работает ли роль против песочницы брокера.
  bool get isSandbox => this == TInvestRole.sandbox;

  static TInvestRole parse(String? value) => TInvestRole.values
      .where((r) => r.slot == value)
      .firstOrNull ??
      TInvestRole.sandbox;
}
