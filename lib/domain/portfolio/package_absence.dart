/// Почему на месте пакета пусто.
///
/// Пустой экран обязан называть причину, и причины здесь разные не оттенком,
/// а тем, что владельцу делать дальше:
///
/// * вариант не прошёл проверку на истории — лечится соседней вкладкой;
/// * составы посчитаны, но на другой горизонт — соседним переключателем;
/// * не посчитано ничего — не лечится ничем и требует объяснения от движка.
///
/// Раньше вторая и третья сливались в одну пустую строку. Движок отдаёт
/// `reason` только когда под запрос не подошёл **ни один** состав; экран же
/// фильтрует ещё и по горизонту, и по варианту. Составы были — просто не те,
/// `reason` приходил пустым, и экран показывал зелёный конвейер, «составов 2»
/// и молчание под ними. Исправная машина, которая ничего не выдаёт, — худший
/// вид пустого экрана: он не называет ни причины, ни действия.
library;

/// Что написать вместо состава.
///
/// [readyVariants] — названия вариантов, которые на выбранном горизонте
/// собрались; [otherHorizons] — годы, на которые составы есть, кроме
/// выбранного; [horizonLabel] — как называется выбранный горизонт на экране;
/// [reason] — что ответил движок, когда не подошло ничего.
String packageAbsenceNote({
  required List<String> readyVariants,
  required List<int> otherHorizons,
  required String horizonLabel,
  required String reason,
}) {
  if (readyVariants.isNotEmpty) {
    return 'Этот вариант проверку на истории не прошёл. Посчитаны: '
        '${readyVariants.map((v) => v.toLowerCase()).join(', ')}.';
  }
  if (otherHorizons.isNotEmpty) {
    final years = [...otherHorizons]..sort();
    final where = years.length == 1
        ? '${years.first} ${yearsWord(years.first)}'
        : '${years.join(' и ')} лет';
    return 'На горизонт «$horizonLabel» состава нет: посчитанные составы — '
        'на $where. Переключите горизонт или пересчитайте.';
  }
  return reason.isEmpty
      ? 'Состав ещё не посчитан. Шаги сборки — ниже: работа стоит на первом, '
          'у которого нет отметки.'
      : reason;
}

/// «год / года / лет» — падеж по числу.
String yearsWord(int value) {
  final tail = value % 100;
  if (tail >= 11 && tail <= 14) return 'лет';
  return switch (value % 10) {
    1 => 'год',
    2 || 3 || 4 => 'года',
    _ => 'лет',
  };
}
